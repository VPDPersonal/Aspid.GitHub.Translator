// Builds the extension icons from the Aspid snake on its dark tile (aspid-snake-tile.jpg, a smooth
// rendition of the Aspid.FastTools snake in aspid-snake.png).
// - icon.svg: the snake's tile, with "文" and "A" in the two holes of its coil, outlined in the tile's colour,
//   for 128 px and the settings page;
// - icon-tile.svg: the same with bigger, bolder glyphs, for 48 px;
// - icon-small.svg: the glyphs alone, in the snake's green, for the 16 and 32 px toolbar icons, where the
//   snake would be too small to read.
// The image is embedded, because an SVG loaded through <img> (the promo tiles) cannot fetch other files.
// It is a JPEG: the tile is opaque (its corners are clipped here), and a PNG would be five times larger.
// Run `npm run icons` after a change; index.mjs renders the PNGs from the SVGs this writes.
import { readFile, writeFile } from 'node:fs/promises';

const dir = new URL('./', import.meta.url);
const snake = `data:image/jpeg;base64,${(await readFile(new URL('aspid-snake-tile.jpg', dir))).toString('base64')}`;

const TILE = ['#16241b', '#0c1410'];
const GLYPH = '#e8f5ec';
// The snake's greens for the small icons, a shade darker than its bright and middle facets
// (#7cdc87, #31904a), so the light end still reads on a light toolbar.
const SNAKE = ['#5ec96c', '#2b8a45'];

// "文" and "A", drawn around (60, 30.25) and (35, 63).
const WEN = `<path d="M60 16.5 V19.5"/>
      <path d="M49 24 H71"/>
      <path d="M66.5 27 Q62.5 37.5 49 44"/>
      <path d="M53.5 27 Q57.5 37.5 71 44"/>`;
const A = `<path d="M26 74 L35 52 L44 74"/>
      <path d="M29 67 H41"/>`;

// The image's own tile has rounder corners than ours, so it is drawn a little larger than the tile
// and its black corners fall outside the clip.
const ZOOM = 1.035;
const IMAGE = { at: (96 * (1 - ZOOM)) / 2, size: 96 * ZOOM };
// The glyphs in the holes of the coil: their scale, centres and strokes (in the glyphs' units).
// "文" sits in the upper hole, below the head (around 33-58 x 15-27), so the eye stays visible;
// "A" in the lower one. `outline` is the dark outline round the stroke.
const FRONT = { scale: 0.76, wen: '36.5 43', a: '61 63.5', stroke: 6, outline: 10 };
// At 48 px the glyphs are bigger and bolder, and overlap the coil more.
const FRONT_48 = { scale: 0.86, wen: '36 44', a: '61.5 64', stroke: 7, outline: 10.5 };

const gradient = (id, [from, to]) => `
    <linearGradient id="${id}" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="96" y2="96">
      <stop offset="0" stop-color="${from}"/>
      <stop offset="1" stop-color="${to}"/>
    </linearGradient>`;

const tile = `<rect width="96" height="96" rx="22" fill="url(#tile)"/>
  <!-- A faint rim, so the dark tile does not vanish on dark pages. -->
  <rect x="0.5" y="0.5" width="95" height="95" rx="21.5" fill="none" stroke="#fff" stroke-opacity="0.08"/>`;

const frontGlyphs = (front, attributes) => `<g fill="none" ${attributes} stroke-linecap="round" stroke-linejoin="round">
    <g transform="translate(${front.wen}) scale(${front.scale}) translate(-60 -30.25)">
      ${WEN}
    </g>
    <g transform="translate(${front.a}) scale(${front.scale}) translate(-35 -63)">
      ${A}
    </g>
  </g>`;

const snakeIcon = (front) => `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96">
  <!-- Generated by packages/brand/icon.mjs, do not edit by hand. -->
  <defs>${gradient('tile', TILE)}
    <clipPath id="clip"><rect width="96" height="96" rx="22"/></clipPath>
    <!-- A soft shadow under the outline, lifting the glyphs off the snake. -->
    <filter id="shadow" x="-20%" y="-20%" width="140%" height="140%">
      <feGaussianBlur in="SourceAlpha" stdDeviation="1.6"/>
      <feOffset dy="1"/>
      <feComponentTransfer><feFuncA type="linear" slope="0.7"/></feComponentTransfer>
      <feMerge><feMergeNode/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
  </defs>
  ${tile}
  <image x="${IMAGE.at.toFixed(2)}" y="${IMAGE.at.toFixed(2)}" width="${IMAGE.size.toFixed(2)}" height="${IMAGE.size.toFixed(2)}" clip-path="url(#clip)" href="${snake}"/>
  <!-- The rim again, over the image. -->
  <rect x="0.5" y="0.5" width="95" height="95" rx="21.5" fill="none" stroke="#fff" stroke-opacity="0.08"/>
  ${frontGlyphs(front, `stroke="${TILE[1]}" stroke-width="${front.outline}" filter="url(#shadow)"`)}
  ${frontGlyphs(front, `stroke="${GLYPH}" stroke-width="${front.stroke}"`)}
</svg>
`;

// The glyphs alone, as big as the square allows: "文" top left, "A" bottom right, like on icon.svg.
// GLYPH_SCALE is the scale of the paths above, and the stroke width is in their units, so it scales with them.
// The glyphs are a mask over a square of the snake's gradient, so the gradient runs across both of them
// (on the strokes themselves it would follow each glyph's scaled coordinates).
const GLYPH_SCALE = 1.7;
const glyphMask = (stroke) => `<mask id="glyphs" maskUnits="userSpaceOnUse" x="0" y="0" width="96" height="96">
      <g fill="none" stroke="#fff" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round">
        <g transform="translate(27 31) scale(${GLYPH_SCALE}) translate(-60 -30.25)">
          ${WEN.replaceAll('\n', '\n    ')}
        </g>
        <g transform="translate(71 70) scale(${GLYPH_SCALE}) translate(-35 -63)">
          ${A.replaceAll('\n', '\n    ')}
        </g>
      </g>
    </mask>`;
const glyphs = '<rect width="96" height="96" fill="url(#snake)" mask="url(#glyphs)"/>';

const small = `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96">
  <!-- Generated by packages/brand/icon.mjs, do not edit by hand. -->
  <defs>${gradient('snake', SNAKE)}
    ${glyphMask(6.5)}
  </defs>
  ${glyphs}
</svg>
`;

await writeFile(new URL('icon.svg', dir), snakeIcon(FRONT));
await writeFile(new URL('icon-tile.svg', dir), snakeIcon(FRONT_48));
await writeFile(new URL('icon-small.svg', dir), small);
