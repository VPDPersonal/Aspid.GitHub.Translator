// Builds the extension icons from the Aspid snake (assets/aspid-snake.png, the logo of Aspid.FastTools).
// - icon.svg: the snake on a dark tile, with "文" and "A" over it, outlined in the tile's colour, for 128 px and the settings page;
// - icon-tile.svg: "文" and "A" alone on the tile, in the snake's green, for 48 px;
// - icon-small.svg: the same glyphs without the tile, for the 16 and 32 px toolbar icons.
// The small sizes drop the snake: its faceted texture turns into noise below 48 px.
// The PNG is embedded, because an SVG loaded through <img> (the promo tiles) cannot fetch other files.
// Run `npm run icons` after a change; build.mjs renders the PNGs from the SVGs this writes.
import { readFile, writeFile } from 'node:fs/promises';

const dir = new URL('./', import.meta.url);
const snake = `data:image/png;base64,${(await readFile(new URL('aspid-snake.png', dir))).toString('base64')}`;
const ASPECT = 254 / 256; // height / width of aspid-snake.png

const TILE = ['#16241b', '#0c1410'];
const GLYPH = '#e8f5ec';
// The snake's greens for the small icons, a shade darker than its bright and middle facets
// (#7cdc87, #31904a), so the light end still reads on a light toolbar.
const SNAKE = ['#5ec96c', '#2b8a45'];

// "文" and "A", drawn around (60, 30.25) and (35, 63).
const WEN = `<path d="M60 16.5 V19.5"/>
      <path d="M49 24 H71"/>
      <path d="M66.5 27 Q62.5 37.5 49 44"/>
      <path d="M53.5 27 Q57.5 37.5 71 44"/>`;
const A = `<path d="M26 74 L35 52 L44 74"/>
      <path d="M29 67 H41"/>`;

// The snake on the tile: its width and top left corner in the 96 px drawing.
const SIZE = 86;
const X = (96 - SIZE) / 2;
const Y = (96 - SIZE * ASPECT) / 2;
// The glyphs over the snake: their scale, centres and strokes (in the glyphs' units). "文" stays
// left of and below the snake's head (around 37-56 x 14-26), so the eye stays visible.
const FRONT_SCALE = 1.05;
const FRONT_WEN = '30 42';
const FRONT_A = '66 66';
const FRONT_STROKE = 5.5;
const FRONT_OUTLINE = 10.5; // the dark outline, about 2.5 units on each side of the stroke

const gradient = (id, [from, to]) => `
    <linearGradient id="${id}" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="96" y2="96">
      <stop offset="0" stop-color="${from}"/>
      <stop offset="1" stop-color="${to}"/>
    </linearGradient>`;

const tile = `<rect width="96" height="96" rx="22" fill="url(#tile)"/>
  <!-- A faint rim, so the dark tile does not vanish on dark pages. -->
  <rect x="0.5" y="0.5" width="95" height="95" rx="21.5" fill="none" stroke="#fff" stroke-opacity="0.08"/>`;

const frontGlyphs = (attributes) => `<g fill="none" ${attributes} stroke-linecap="round" stroke-linejoin="round">
    <g transform="translate(${FRONT_WEN}) scale(${FRONT_SCALE}) translate(-60 -30.25)">
      ${WEN}
    </g>
    <g transform="translate(${FRONT_A}) scale(${FRONT_SCALE}) translate(-35 -63)">
      ${A}
    </g>
  </g>`;

const icon = `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96">
  <!-- Generated by assets/icon.mjs, do not edit by hand. -->
  <defs>${gradient('tile', TILE)}
    <!-- A soft shadow under the outline, lifting the glyphs off the snake. -->
    <filter id="shadow" x="-20%" y="-20%" width="140%" height="140%">
      <feGaussianBlur in="SourceAlpha" stdDeviation="1.6"/>
      <feOffset dy="1"/>
      <feComponentTransfer><feFuncA type="linear" slope="0.7"/></feComponentTransfer>
      <feMerge><feMergeNode/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
  </defs>
  ${tile}
  <image x="${X}" y="${Y.toFixed(2)}" width="${SIZE}" height="${(SIZE * ASPECT).toFixed(2)}" href="${snake}"/>
  ${frontGlyphs(`stroke="${TILE[1]}" stroke-width="${FRONT_OUTLINE}" filter="url(#shadow)"`)}
  ${frontGlyphs(`stroke="${GLYPH}" stroke-width="${FRONT_STROKE}"`)}
</svg>
`;

// The glyphs alone, as big as the square allows: "文" top left, "A" bottom right, like on icon.svg.
// GLYPH_SCALE is the scale of the paths above, and the stroke width is in their units, so it scales with them.
// The glyphs are a mask over a square of the snake's gradient, so the gradient runs across both of them
// (on the strokes themselves it would follow each glyph's scaled coordinates).
const GLYPH_SCALE = 1.7;
const glyphMask = (stroke) => `<mask id="glyphs" maskUnits="userSpaceOnUse" x="0" y="0" width="96" height="96">
      <g fill="none" stroke="#fff" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round">
        <g transform="translate(27 31) scale(${GLYPH_SCALE}) translate(-60 -30.25)">
          ${WEN.replaceAll('\n', '\n    ')}
        </g>
        <g transform="translate(71 70) scale(${GLYPH_SCALE}) translate(-35 -63)">
          ${A.replaceAll('\n', '\n    ')}
        </g>
      </g>
    </mask>`;
const glyphs = '<rect width="96" height="96" fill="url(#snake)" mask="url(#glyphs)"/>';

const iconTile = `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96">
  <!-- Generated by assets/icon.mjs, do not edit by hand. -->
  <defs>${gradient('tile', TILE)}${gradient('snake', SNAKE)}
    ${glyphMask(6)}
  </defs>
  ${tile}
  <g transform="translate(48 48) scale(0.78) translate(-48 -48)">
    ${glyphs}
  </g>
</svg>
`;

const small = `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96">
  <!-- Generated by assets/icon.mjs, do not edit by hand. -->
  <defs>${gradient('snake', SNAKE)}
    ${glyphMask(6.5)}
  </defs>
  ${glyphs}
</svg>
`;

await writeFile(new URL('icon.svg', dir), icon);
await writeFile(new URL('icon-tile.svg', dir), iconTile);
await writeFile(new URL('icon-small.svg', dir), small);
